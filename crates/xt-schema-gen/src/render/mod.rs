mod hierarchy;
mod metadata;
mod nodes;
mod pointers;
mod spec;

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
    path::PathBuf,
};

use xt_parser::schema::Schema;

use crate::{
    GeneratedSchema, SourceIdentity,
    hierarchy::HierarchyPlan,
    naming::{module_identifier, pascal_case},
};

pub(crate) struct RenderContext<'a> {
    pub schema: &'a Schema,
    pub identity: &'a SourceIdentity,
    pub hierarchy: &'a HierarchyPlan,
    pub module_name: String,
    pub rust_names: BTreeMap<u16, String>,
    pub abstract_classes: BTreeSet<u16>,
}

impl<'a> RenderContext<'a> {
    fn new(schema: &'a Schema, identity: &'a SourceIdentity, hierarchy: &'a HierarchyPlan) -> Self {
        Self {
            schema,
            identity,
            hierarchy,
            module_name: module_identifier(&schema.key),
            rust_names: schema
                .nodes
                .iter()
                .map(|node| (node.node_type, pascal_case(&node.name)))
                .collect(),
            abstract_classes: schema
                .nodes
                .iter()
                .flat_map(|node| &node.fields)
                .filter_map(|field| (field.pointer_class >= 1000).then_some(field.pointer_class))
                .collect(),
        }
    }

    pub fn header(&self) -> String {
        format!(
            "// @generated by xt-schema-gen. Do not edit by hand.\n\
             // Source: {}\n\
             // Source SHA-256: {}\n\
             // LF-normalized SHA-256: {}\n\n",
            self.identity.source_name, self.identity.source_sha256, self.identity.normalized_sha256
        )
    }

    pub fn node_name(&self, node_type: u16) -> &str {
        &self.rust_names[&node_type]
    }

    pub fn pointer_alias(&self, pointer_class: u16) -> String {
        if pointer_class == 0 {
            return "AnyNode".to_owned();
        }
        if pointer_class < 1000 {
            return self.rust_names.get(&pointer_class).map_or_else(
                || format!("UnknownNode{pointer_class}"),
                |name| format!("{name}Node"),
            );
        }
        self.hierarchy.family(pointer_class).map_or_else(
            || format!("PointerClass{pointer_class}"),
            |family| family.pointer_alias.clone(),
        )
    }
}

pub(crate) fn render_schema(
    schema: &Schema,
    identity: &SourceIdentity,
    hierarchy: &HierarchyPlan,
) -> Result<GeneratedSchema, String> {
    let context = RenderContext::new(schema, identity, hierarchy);
    let mut files = BTreeMap::new();

    files.insert(PathBuf::from("mod.rs"), render_module(&context));
    files.insert(PathBuf::from("metadata.rs"), metadata::render(&context));
    files.insert(PathBuf::from("spec.rs"), spec::render(&context));
    files.insert(PathBuf::from("pointers.rs"), pointers::render(&context));
    files.insert(PathBuf::from("hierarchy.rs"), hierarchy::render(&context));
    nodes::render(&context, &mut files)?;

    Ok(GeneratedSchema {
        module_name: context.module_name,
        files,
    })
}

fn render_module(context: &RenderContext<'_>) -> String {
    let mut output = context.header();
    output.push_str(
        "pub mod hierarchy;\n\
         pub mod metadata;\n\
         pub mod nodes;\n\
         pub mod pointers;\n\
         pub mod spec;\n\n\
         pub use nodes::Node;\n\
         pub use spec::SCHEMA;\n",
    );
    output
}

pub(crate) fn write_generated_doc(output: &mut String, text: &str) {
    for line in text.lines() {
        writeln!(output, "/// {line}").unwrap();
    }
}
