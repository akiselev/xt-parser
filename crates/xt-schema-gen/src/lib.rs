use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

use sha2::{Digest, Sha256};
use xt_parser::schema::SchemaFile;

pub use hierarchy::{HierarchyPlan, NodeFamily, infer_hierarchy};

const GENERATED_BANNER: &str = "// @generated by xt-schema-gen. Do not edit by hand.";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceIdentity {
    pub source_name: String,
    pub source_sha256: String,
    pub normalized_sha256: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedSchema {
    pub module_name: String,
    pub files: BTreeMap<PathBuf, String>,
}

pub fn generate_schema(input: &[u8], source_name: &str) -> Result<GeneratedSchema, String> {
    let source_sha256 = format!("{:x}", Sha256::digest(input));
    let normalized = input
        .iter()
        .copied()
        .filter(|byte| *byte != b'\r')
        .collect::<Vec<_>>();
    let normalized_sha256 = format!("{:x}", Sha256::digest(&normalized));
    let schema_file = SchemaFile::parse(input).map_err(|error| error.to_string())?;
    let schema = schema_file
        .to_schema(Some(source_sha256.clone()), Some(normalized_sha256.clone()))
        .map_err(|error| error.to_string())?;
    let identity = SourceIdentity {
        source_name: source_name.to_owned(),
        source_sha256,
        normalized_sha256,
    };
    let hierarchy = infer_hierarchy(&schema);
    render::render_schema(&schema, &identity, &hierarchy)
}

/// Replace one generated schema directory.
///
/// Existing content is removed only when the directory name matches the
/// generated schema module and every contained file carries the generator
/// banner. This prevents a mistaken output argument from deleting handwritten
/// source.
pub fn materialize(generated: &GeneratedSchema, output: &Path) -> Result<(), String> {
    if output.file_name().and_then(|name| name.to_str()) != Some(&generated.module_name) {
        return Err(format!(
            "output directory must end in {}, got {}",
            generated.module_name,
            output.display()
        ));
    }
    if output.exists() {
        verify_generated_tree(output)?;
        fs::remove_dir_all(output)
            .map_err(|error| format!("remove generated {}: {error}", output.display()))?;
    }
    fs::create_dir_all(output).map_err(|error| format!("create {}: {error}", output.display()))?;
    for (relative_path, contents) in &generated.files {
        let path = output.join(relative_path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| format!("create {}: {error}", parent.display()))?;
        }
        fs::write(&path, contents).map_err(|error| format!("write {}: {error}", path.display()))?;
    }
    Ok(())
}

fn verify_generated_tree(path: &Path) -> Result<(), String> {
    if !path.is_dir() {
        return Err(format!("{} exists but is not a directory", path.display()));
    }
    let mut pending = vec![path.to_owned()];
    while let Some(directory) = pending.pop() {
        for entry in
            fs::read_dir(&directory).map_err(|error| format!("{}: {error}", directory.display()))?
        {
            let entry = entry.map_err(|error| format!("{}: {error}", directory.display()))?;
            let file_type = entry
                .file_type()
                .map_err(|error| format!("{}: {error}", entry.path().display()))?;
            if file_type.is_symlink() {
                return Err(format!(
                    "refusing to replace generated tree containing symlink {}",
                    entry.path().display()
                ));
            }
            if file_type.is_dir() {
                pending.push(entry.path());
                continue;
            }
            if !file_type.is_file() {
                return Err(format!(
                    "refusing to replace generated tree containing special file {}",
                    entry.path().display()
                ));
            }
            let contents = fs::read_to_string(entry.path())
                .map_err(|error| format!("{}: {error}", entry.path().display()))?;
            if !contents.starts_with(GENERATED_BANNER) {
                return Err(format!(
                    "refusing to replace handwritten file {}",
                    entry.path().display()
                ));
            }
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const TEST_SCHEMA: &[u8] = b"preamble\n\
**PART1;FORMAT=text;GUISE=schema;KEY=SCH_TEST;\n\
**PART2;\n\
**PART3;\n\
**END_OF_HEADER***\n\
T \n\
1 \n\
: SCHEMA FILE created for test; \n\
4 3 5 0 \n\
1 PLANE; Plane; 1 2 0 \n\
next; p; 1 1006 0 \n\
previous; p; 1 1006 0 \n\
2 SPHERE; Sphere; 1 2 0 \n\
next; p; 1 1006 0 \n\
previous; p; 1 1006 0 \n\
3 FACE; Face; 1 1 0 \n\
surface; p; 1 1006 0 \n\
**************** end of schema SCH_TEST **************** \n";

    #[test]
    fn emits_separated_metadata_specs_pointers_hierarchy_and_nodes() {
        let generated = generate_schema(TEST_SCHEMA, "sch_test.s_t").unwrap();
        let paths = generated
            .files
            .keys()
            .map(|path| path.to_string_lossy().into_owned())
            .collect::<Vec<_>>();
        assert_eq!(generated.module_name, "sch_test");
        assert!(paths.contains(&"metadata.rs".to_owned()));
        assert!(paths.contains(&"spec.rs".to_owned()));
        assert!(paths.contains(&"pointers.rs".to_owned()));
        assert!(paths.contains(&"hierarchy.rs".to_owned()));
        assert!(paths.contains(&"nodes/mod.rs".to_owned()));
        assert!(paths.contains(&"nodes/standalone.rs".to_owned()));
        assert!(paths.contains(&"nodes/families/class_1006_surface.rs".to_owned()));

        let hierarchy = &generated.files[Path::new("hierarchy.rs")];
        assert!(hierarchy.contains("pub trait SurfaceFamily"));
        assert!(hierarchy.contains("label_source_field: Some(\"surface\")"));
        let family = &generated.files[Path::new("nodes/families/class_1006_surface.rs")];
        assert!(family.contains("pub struct Plane"));
        assert!(family.contains("pub struct Sphere"));
        assert!(!family.contains("pub struct Face"));
        assert!(generated.files[Path::new("nodes/standalone.rs")].contains("pub struct Face"));
    }
}
